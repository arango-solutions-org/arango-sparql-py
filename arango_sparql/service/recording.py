"""Recording the questions asked under a control plane (its FR-6.7, FR-14.4).

Each route that runs a query calls :func:`record_question` once the query has run and
before answering. Outside a control plane it does nothing. Under one, the question is
recorded in the project's history: who asked (from the context), its words when it was
asked in words, and the SPARQL it ran. A question that cannot be recorded is not answered:
503 ``E_QUESTION_NOT_RECORDED``, and the rows are not returned.

The words are the tool's to vouch for, not the caller's. ``/nl-translate`` remembers the
words it generated each query from (:func:`remember_generated`); a run that sends words with
its query (``/execute``, ``/profile``) has them recorded only when this session generated
that query from those words, and is otherwise recorded as a written query.

The page's graph view runs the question it just asked again, widened (``graph: true``).
That run is the same question: it is recorded only when this session has not recorded the
same words and query within :data:`AGAIN_SECONDS`, so a caller cannot read through the graph
run unrecorded, and the page's own graph run does not record the question twice.
"""

from __future__ import annotations

import hashlib
import logging
import threading
import time
from typing import Any

from fastapi import HTTPException, Request

from . import control_plane

logger = logging.getLogger("arango_sparql.service.recording")

#: How long after a question is recorded a re-run of it for the graph view is the same ask.
AGAIN_SECONDS = 600.0

#: How many generated questions a session remembers, the newest kept: enough for the page's
#: history of recent asks, and a bound on what one session holds.
GENERATED_KEPT = 64

NOT_RECORDED = "E_QUESTION_NOT_RECORDED"

# A session's requests run on several threads at once; its two maps change only under this.
_lock = threading.Lock()


def _key(question: str | None, query: str) -> str:
    return hashlib.sha256(f"{question or ''}\0{query}".encode()).hexdigest()


def remember_generated(session: Any, *, question: str, query: str) -> None:
    """Remember that this session generated *query* from *question*, so a run of that query,
    unedited, may carry the words (:func:`record_question` with ``client_words``)."""
    if not control_plane.mode():
        return
    generated: dict[str, None] | None = getattr(session, "generated_questions", None)
    if generated is None:
        return
    key = _key(question, query)
    with _lock:
        generated.pop(key, None)
        generated[key] = None
        while len(generated) > GENERATED_KEPT:
            generated.pop(next(iter(generated)))


def record_question(
    request: Request,
    session: Any,
    *,
    query: str,
    question: str | None = None,
    again: bool = False,
    client_words: bool = False,
) -> None:
    """Record *query* (asked as *question*, or written) for the request's context. With
    *again*, a re-run of a question this session recorded recently is not recorded twice.
    With *client_words*, *question* came from the caller and is kept only when this session
    generated *query* from it. Raises :class:`HTTPException` 503 when it cannot be recorded."""
    if not control_plane.mode():
        return
    if client_words and question is not None:
        generated: dict[str, None] | None = getattr(session, "generated_questions", None)
        with _lock:
            vouched = generated is not None and _key(question, query) in generated
        if not vouched:
            logger.info("question words not generated by this session for this query; recorded as written")
            question = None
    recent: dict[str, float] | None = getattr(session, "recorded_questions", None)
    key = _key(question, query)
    now = time.monotonic()
    if again and recent is not None:
        with _lock:
            at = recent.get(key, float("-inf"))
        if now - at < AGAIN_SECONDS:
            return
    try:
        control_plane.record_question(request.headers, question=question, query=query)
    except control_plane.QuestionNotRecorded as exc:
        raise HTTPException(
            status_code=503,
            detail={
                "error": "The question could not be recorded in the project's history, so it "
                f"is not answered: {exc}",
                "code": NOT_RECORDED,
            },
        ) from exc
    if recent is not None:
        with _lock:
            for old in [k for k, at in recent.items() if now - at >= AGAIN_SECONDS]:
                del recent[old]
            recent[key] = now
